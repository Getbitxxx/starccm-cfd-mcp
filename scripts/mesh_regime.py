"""F3: deterministic snapshot of the GRANDFATHERED CaseSpecs (2026-10-30 mesh family-gate regime).

The 2026-10-30 standard says every CaseSpec must declare quality.mesh_acceptance.  The ~60 CaseSpecs
that already existed on that date are grandfathered BY EXACT BYTES - not by "it is old" - so the
standard cannot be applied retroactively and, equally, an edited old CaseSpec cannot sneak out from
under it.  This script is the only writer of the pin:

    campaigns/uav-2026/case-regime-legacy.json

    {"schema_version": 1, "kind": "case_regime_legacy", "snapshot_date": "YYYY-MM-DD",
     "entries": [{"case_id", "case_spec_path", "sha256", "canonical_sha256"}]}

`sha256` is the file sha256; `canonical_sha256` is the sha256 of the canonical JSON payload (the
same encoding validate_case_spec digests with), which is what lets the rule recognise a parsed dict
that is not tied to a path.  Entries are sorted by case_spec_path; nothing else varies run to run, so
the committed snapshot reproduces byte for byte.

Safety on write (fail closed):
  - changing the pinned bytes of an EXISTING entry is refused (that is the failure mode the pin
    exists to catch: editing an old case must force the block or a recorded exception);
  - a NEW CaseSpec that declares no quality.mesh_acceptance is refused (adding it would launder a
    non-compliant spec into "legacy");
  - `--force` records the exception in the commit diff instead of silently re-pinning.  It is for a
    reviewed split/exception decision only.

CLI:
    python3 scripts/mesh_regime.py --snapshot [--snapshot-date YYYY-MM-DD] [--root .] [--force]
    python3 scripts/mesh_regime.py --check    [--root .]

`--check` is about the HISTORICAL pin: it passes when no pinned entry changed and none disappeared,
and it reports post-split CaseSpecs under `new` (those are allowed only because they declare the
family block; `write_guard` refuses re-pinning a new block-less spec).  Byte reproduction of the whole
snapshot file is reported separately as `identical` (false once a post-split case exists, which is
expected and is never "fixed" by rewriting the historical file).  Updated 2026-10-31 when the first
signed Phase 3 case (uav-crm-hl-hlpw4) declared the block.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from plan_mesh_gate import (
    LEGACY_SNAPSHOT_REL,
    SNAPSHOT_SCHEMA_VERSION,
    MeshRegimeError,
    canonical_spec_sha256,
    load_legacy_snapshot,
    snapshot_file,
    validate_snapshot,
)

ROOT = Path(__file__).resolve().parents[1]


def repo_root(root: str | Path | None = None) -> Path:
    return Path(root).resolve() if root is not None else ROOT


def iter_case_specs(root: str | Path | None = None) -> list[Path]:
    """Every cases/**/case_spec*.json, sorted by repo-relative posix path (deterministic)."""
    root = repo_root(root)
    cases = root / 'cases'
    if not cases.is_dir():
        raise SystemExit(f'cases directory missing: {cases}')
    paths = [path for path in cases.rglob('case_spec*.json') if path.is_file()]
    return sorted(paths, key=lambda path: path.relative_to(root).as_posix())


def case_id_for(path: Path, root: str | Path | None = None) -> str:
    """The case directory relative to cases/ (e.g. 'uav-prop-apc10x7e', 'a/b/mesh/coarse')."""
    root = repo_root(root)
    return path.parent.relative_to(root / 'cases').as_posix()


def build_snapshot(root: str | Path | None = None, snapshot_date: str = '2026-10-30') -> dict:
    """Build the snapshot document from the current tree (pure: reads nothing else, writes nothing)."""
    root = repo_root(root)
    entries = []
    for path in iter_case_specs(root):
        data = path.read_bytes()
        try:
            spec = json.loads(data)
        except json.JSONDecodeError as exc:
            raise SystemExit(f'cannot snapshot {path.relative_to(root).as_posix()}: {exc}')
        entries.append({
            'case_id': case_id_for(path, root),
            'case_spec_path': path.relative_to(root).as_posix(),
            'sha256': hashlib.sha256(data).hexdigest(),
            'canonical_sha256': canonical_spec_sha256(spec),
        })
    return {
        'schema_version': SNAPSHOT_SCHEMA_VERSION,
        'kind': 'case_regime_legacy',
        'snapshot_date': snapshot_date,
        'note': ('Grandfathered CaseSpecs are byte-identical to this snapshot. Any change forces '
                 'quality.mesh_acceptance or a recorded exception; a NEW CaseSpec must declare the '
                 'block. Generated by scripts/mesh_regime.py --snapshot (sorted, deterministic).'),
        'entries': entries,
    }


def serialize(document: dict) -> bytes:
    return (json.dumps(document, indent=1, ensure_ascii=False) + '\n').encode('utf-8')


def _declares_block(spec_path: Path) -> bool:
    try:
        spec = json.loads(spec_path.read_text(encoding='utf-8'))
    except (OSError, json.JSONDecodeError):
        return False
    quality = spec.get('quality')
    return isinstance(quality, dict) and isinstance(quality.get('mesh_acceptance'), dict)


def write_guard(existing: dict | None, candidate: dict, root: str | Path | None = None) -> list[str]:
    """Why overwriting an existing snapshot with `candidate` must be refused ([] = allowed)."""
    if existing is None:
        return []
    root = repo_root(root)
    problems: list[str] = []
    old = {entry['case_spec_path']: entry for entry in existing['entries']}
    new = {entry['case_spec_path']: entry for entry in candidate['entries']}
    for relative in sorted(set(old) & set(new)):
        if old[relative]['sha256'] != new[relative]['sha256'] or \
                old[relative]['canonical_sha256'] != new[relative]['canonical_sha256']:
            problems.append(f'CHANGED_LEGACY_SPEC {relative}')
    for relative in sorted(set(new) - set(old)):
        spec_path = root / relative
        if not _declares_block(spec_path):
            problems.append(f'NEW_SPEC_WITHOUT_BLOCK {relative}')
    return problems


def write_snapshot(root: str | Path | None = None, snapshot_date: str | None = None,
                   force: bool = False) -> dict:
    root = repo_root(root)
    existing = None
    path = snapshot_file(root)
    if path.is_file():
        try:
            existing = load_legacy_snapshot(root)
        except MeshRegimeError as exc:
            raise SystemExit(f'existing snapshot is invalid, refusing to overwrite: {exc}')
    if snapshot_date is None:
        snapshot_date = existing['snapshot_date'] if existing else '2026-10-30'
    candidate = build_snapshot(root, snapshot_date)
    errors = validate_snapshot(candidate)
    if errors:  # pragma: no cover - build_snapshot produces a valid document by construction
        raise SystemExit('refusing to write an invalid snapshot: ' + '; '.join(errors))
    problems = write_guard(existing, candidate, root)
    if problems and not force:
        raise SystemExit('refusing to re-pin the legacy snapshot:\n  ' + '\n  '.join(problems)
                         + '\nuse --force only for a reviewed split/exception decision')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(serialize(candidate))
    return candidate


def check_snapshot(root: str | Path | None = None) -> dict:
    root = repo_root(root)
    path = snapshot_file(root)
    try:
        existing = load_legacy_snapshot(root)
    except MeshRegimeError as exc:
        return {'ok': False, 'snapshot': LEGACY_SNAPSHOT_REL, 'error': exc.message, 'code': exc.code,
                'changed': [], 'new': [], 'missing': []}
    rebuilt = build_snapshot(root, existing['snapshot_date'])
    identical = serialize(rebuilt) == serialize(existing)
    old = {entry['case_spec_path']: entry['sha256'] for entry in existing['entries']}
    new = {entry['case_spec_path']: entry['sha256'] for entry in rebuilt['entries']}
    changed = sorted(relative for relative in set(old) & set(new) if old[relative] != new[relative])
    missing = sorted(set(old) - set(new))
    added = sorted(set(new) - set(old))
    return {
        # The snapshot is HISTORICAL: a post-split CaseSpec that declares the family block is allowed
        # (write_guard has always said so), so "ok" means no historical entry changed and none vanished.
        # `identical` is reported separately for callers that want byte reproduction of the whole file.
        'ok': not changed and not missing,
        'identical': identical,
        'snapshot': path.relative_to(root).as_posix(),
        'snapshot_date': existing['snapshot_date'],
        'entries': len(existing['entries']),
        'changed': changed,
        'new': added,
        'missing': missing,
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description='Snapshot/check the grandfathered CaseSpec pin (2026-10-30 mesh family-gate regime)')
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--snapshot', action='store_true', help='write the deterministic snapshot')
    action.add_argument('--check', action='store_true', help='verify the historical pin (changed/missing must be empty; post-split new specs are listed)')
    parser.add_argument('--root', default=None, help='repo root (default: this checkout)')
    parser.add_argument('--snapshot-date', default=None, help='split date to record (default: keep/2026-10-30)')
    parser.add_argument('--force', action='store_true', help='allow re-pinning a changed/new legacy entry')
    args = parser.parse_args(argv)
    if args.snapshot:
        document = write_snapshot(args.root, args.snapshot_date, args.force)
        print(json.dumps({'snapshot': LEGACY_SNAPSHOT_REL, 'snapshot_date': document['snapshot_date'],
                          'entries': len(document['entries'])}, indent=1))
        return 0
    report = check_snapshot(args.root)
    print(json.dumps(report, indent=1))
    return 0 if report['ok'] else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
